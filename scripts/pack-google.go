// Generate an ignored build-only file. No user credentials belong in this bundle.
// The key travels with the binary: this is obfuscation, not confidential storage.
package main

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"
)

func main() {
	id, secret := os.Getenv("GDRIVE_CLIENT"), os.Getenv("GDRIVE_SECRET")
	keyText, bundle := "", ""
	if (id == "") != (secret == "") {
		panic("set both GDRIVE_CLIENT and GDRIVE_SECRET, or neither")
	}
	if id != "" {
		key := make([]byte, 32)
		if _, err := rand.Read(key); err != nil {
			panic(err)
		}
		block, err := aes.NewCipher(key)
		if err != nil {
			panic(err)
		}
		gcm, err := cipher.NewGCM(block)
		if err != nil {
			panic(err)
		}
		nonce := make([]byte, gcm.NonceSize())
		if _, err := rand.Read(nonce); err != nil {
			panic(err)
		}
		plain, _ := json.Marshal([]string{id, secret})
		bundle = base64.StdEncoding.EncodeToString(gcm.Seal(nonce, nonce, plain, nil))
		keyText = base64.StdEncoding.EncodeToString(key)
	}
	source := fmt.Sprintf("// Code generated by scripts/pack-google.go; DO NOT COMMIT.\npackage main\nfunc init() { defaultGDriveClient, defaultGDriveSecret = decodeGoogleApp(%q, %q) }\n", keyText, bundle)
	if err := os.WriteFile("jarvisd/google_app_generated.go", []byte(source), 0600); err != nil {
		panic(err)
	}
}
